    probabilidad_helada double precision,
    nivel_riesgo text,
    riesgo_severo boolean,
    riesgo_moderado boolean,
    riesgo_inminente boolean,
    temperatura_minima_esperada double precision,
    temperatura_maxima double precision,
    temperatura_atardecer double precision,
    punto_rocio_atardecer double precision,
    bulbo_humedo_atardecer double precision,
    humedad_relativa double precision,
    cobertura_nubosa double precision,
    velocidad_viento double precision,
    umbral_cultivo double precision,
    alerta_cultivo boolean,
    hora_critica_esperada text default '04:00',
    criterio_psicrometro jsonb,
    scores_componentes jsonb,
    factores_contribuyentes jsonb,
    recomendaciones jsonb,
    fuente text default 'modelo_helada_radiativa',
    actualizado timestamptz default now(),
    unique (estacion_id, fecha, cultivo)
);

