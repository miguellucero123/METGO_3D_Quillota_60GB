alter table public.meteo_registros add column if not exists creado_en timestamptz default now();

-- Unique (estacion_id, fecha) si aún no existe
do $$
begin
    if not exists (
        select 1 from pg_constraint
        where conname = 'meteo_registros_estacion_id_fecha_key'
          and conrelid = 'public.meteo_registros'::regclass
    ) then
        alter table public.meteo_registros
            add constraint meteo_registros_estacion_id_fecha_key unique (estacion_id, fecha);
    end if;
exception when others then
    -- Si ya hay otro unique equivalente, no fallar el script
    raise notice 'meteo_registros unique: %', sqlerrm;
end $$;

create index if not exists idx_meteo_registros_estacion_fecha
    on public.meteo_registros (estacion_id, fecha desc);

create index if not exists idx_meteo_registros_fuente
    on public.meteo_registros (fuente);

